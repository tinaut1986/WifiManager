#include "theme.h"

namespace theme
{
    u32 bg          = C2D_Color32(0x0F, 0x14, 0x1B, 0xFF);
    u32 surface     = C2D_Color32(0x1B, 0x24, 0x30, 0xFF);
    u32 surfaceAlt  = C2D_Color32(0x23, 0x30, 0x40, 0xFF);
    u32 overlay     = C2D_Color32(0x00, 0x00, 0x00, 0xB0);

    u32 accent      = C2D_Color32(0x3A, 0x9B, 0xFF, 0xFF);
    u32 accentDim   = C2D_Color32(0x24, 0x5A, 0x8C, 0xFF);
    u32 good        = C2D_Color32(0x3B, 0xD1, 0x7E, 0xFF);
    u32 warn        = C2D_Color32(0xFF, 0xC1, 0x4E, 0xFF);
    u32 danger      = C2D_Color32(0xFF, 0x5C, 0x5C, 0xFF);

    u32 text        = C2D_Color32(0xF2, 0xF5, 0xF8, 0xFF);
    u32 textDim     = C2D_Color32(0x9A, 0xA7, 0xB4, 0xFF);
    u32 textOnAccent= C2D_Color32(0x0B, 0x12, 0x1A, 0xFF);

    void apply(Type t)
    {
        switch (t)
        {
            case Type::Light:
                bg          = C2D_Color32(0xF0, 0xF4, 0xF8, 0xFF);
                surface     = C2D_Color32(0xFF, 0xFF, 0xFF, 0xFF);
                surfaceAlt  = C2D_Color32(0xE2, 0xE8, 0xF0, 0xFF);
                overlay     = C2D_Color32(0x00, 0x00, 0x00, 0x70);

                accent      = C2D_Color32(0x02, 0x84, 0xC7, 0xFF);
                accentDim   = C2D_Color32(0xBA, 0xE6, 0xFD, 0xFF);
                good        = C2D_Color32(0x16, 0xA3, 0x4A, 0xFF);
                warn        = C2D_Color32(0xD9, 0x77, 0x06, 0xFF);
                danger      = C2D_Color32(0xDC, 0x26, 0x26, 0xFF);

                text        = C2D_Color32(0x0F, 0x17, 0x2A, 0xFF);
                textDim     = C2D_Color32(0x64, 0x74, 0x8B, 0xFF);
                textOnAccent= C2D_Color32(0xFF, 0xFF, 0xFF, 0xFF);
                break;

            case Type::Midnight:
                bg          = C2D_Color32(0x00, 0x00, 0x00, 0xFF);
                surface     = C2D_Color32(0x12, 0x12, 0x14, 0xFF);
                surfaceAlt  = C2D_Color32(0x20, 0x20, 0x24, 0xFF);
                overlay     = C2D_Color32(0x00, 0x00, 0x00, 0xD0);

                accent      = C2D_Color32(0x00, 0xD2, 0xFF, 0xFF);
                accentDim   = C2D_Color32(0x00, 0x58, 0x7A, 0xFF);
                good        = C2D_Color32(0x22, 0xC5, 0x5E, 0xFF);
                warn        = C2D_Color32(0xFA, 0xCC, 0x15, 0xFF);
                danger      = C2D_Color32(0xEF, 0x44, 0x44, 0xFF);

                text        = C2D_Color32(0xF8, 0xFA, 0xFC, 0xFF);
                textDim     = C2D_Color32(0x94, 0xA3, 0xB8, 0xFF);
                textOnAccent= C2D_Color32(0x00, 0x00, 0x00, 0xFF);
                break;

            case Type::Dark:
            default:
                bg          = C2D_Color32(0x0F, 0x14, 0x1B, 0xFF);
                surface     = C2D_Color32(0x1B, 0x24, 0x30, 0xFF);
                surfaceAlt  = C2D_Color32(0x23, 0x30, 0x40, 0xFF);
                overlay     = C2D_Color32(0x00, 0x00, 0x00, 0xB0);

                accent      = C2D_Color32(0x3A, 0x9B, 0xFF, 0xFF);
                accentDim   = C2D_Color32(0x24, 0x5A, 0x8C, 0xFF);
                good        = C2D_Color32(0x3B, 0xD1, 0x7E, 0xFF);
                warn        = C2D_Color32(0xFF, 0xC1, 0x4E, 0xFF);
                danger      = C2D_Color32(0xFF, 0x5C, 0x5C, 0xFF);

                text        = C2D_Color32(0xF2, 0xF5, 0xF8, 0xFF);
                textDim     = C2D_Color32(0x9A, 0xA7, 0xB4, 0xFF);
                textOnAccent= C2D_Color32(0x0B, 0x12, 0x1A, 0xFF);
                break;
        }
    }

    const char* name(Type t)
    {
        switch (t)
        {
            case Type::Light:    return "Light";
            case Type::Midnight: return "Midnight";
            case Type::Dark:
            default:             return "Dark";
        }
    }
}
