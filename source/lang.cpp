namespace lang
{
    void init()
    {
        cfguInit();
        u8 sysLangCode = 1;
        if (R_SUCCEEDED(CFGU_GetSystemLanguage(&sysLangCode)))
        {
            switch (sysLangCode)
            {
                case CFG_LANGUAGE_ES: s_sysLang = Id::Spanish; break;
                case CFG_LANGUAGE_FR: s_sysLang = Id::French; break;
                case CFG_LANGUAGE_DE: s_sysLang = Id::German; break;
                case CFG_LANGUAGE_IT: s_sysLang = Id::Italian; break;
                case CFG_LANGUAGE_PT: s_sysLang = Id::Portuguese; break;
                default:              s_sysLang = Id::English; break;
            }
        }
        cfguExit();
    }

    void setLanguage(Id id)
    {
        s_userLang = id;
    }

    Id getLanguage()
    {
        return s_userLang;
    }

    Id effectiveLanguage()
    {
        if (s_userLang == Id::Auto) return s_sysLang;
        return s_userLang;
    }

    const char* name(Id id)
    {
        switch (id)
        {
            case Id::Auto:       return get(STR_LANG_AUTO);
            case Id::English:    return get(STR_LANG_EN);
            case Id::Spanish:    return get(STR_LANG_ES);
            case Id::French:     return get(STR_LANG_FR);
            case Id::German:     return get(STR_LANG_DE);
            case Id::Italian:    return get(STR_LANG_IT);
            case Id::Portuguese: return get(STR_LANG_PT);
            default:             return get(STR_LANG_EN);
        }
    }

    const char* themeName(theme::Type t)
    {
        switch (t)
        {
            case theme::Type::Light:    return get(STR_THEME_LIGHT);
            case theme::Type::Midnight: return get(STR_THEME_MIDNIGHT);
            case theme::Type::Dark:
            default:                    return get(STR_THEME_DARK);
        }
    }

    const char* get(StringKey key)
    {
        Id eff = effectiveLanguage();
        int idx = static_cast<int>(eff);
        if (idx < 1 || idx >= static_cast<int>(Id::COUNT)) idx = static_cast<int>(Id::English);
        return kStrings[idx][key];
    }
}
